"""Generate the compact datasets table (Method, Section III-B), 2026-10-16.

Replaces the former published-baselines table (Table I) after Pedro's review: one row per answer set
with what a reader needs (domain and language, size, the reasoning sample, the human grade, the
guidance material) plus one representative published result as context. Sizes are counted from the
run data (the baseline cell and the reasoning-on samples), never typed by hand; the published results
are the compact rows of published_baselines.csv (source-verified, different models and protocols).

Run:  python -m experiments.analysis.make_datasets_table
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from experiments.analysis import phase5

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT = REPO_ROOT / "article" / "tables" / "tab_datasets.tex"
CORPUS = REPO_ROOT / "data" / "processed" / "corpus.parquet"
STRATA = REPO_ROOT / "data" / "processed" / "_ptcs_strata.parquet"

# (set key, label, domain and language, human grade, guidance, published result)
ROWS = [
    ("mohler:short_answer", "Mohler", "CS short answers (EN)", "0--5, mean of two teachers",
     "reference answer", r"QWK 0.902~\cite{aminah_evaluating_2025}"),
    ("semeval:short_answer", "SemEval", "science short answers (EN)", "correct or incorrect",
     "reference answer", r"QWK 0.767~\cite{chen_cemft_2026}"),
    ("riayn:code", "RIAYN", "data-structures code (EN)", "rubric steps, two graders",
     "rubric", r"Pearson $r$ 0.825~\cite{pathak_rubric_2025}"),
    ("ptcs:code", "PT-CS code", "Java code (PT)", "final grade, two teachers",
     "rubric", "none (new)"),
    ("ptcs:short_answer", "PT-CS short", "theory short answers (PT)", "final grade, two teachers",
     "rubric", "none (new)"),
]


def main() -> int:
    interv = set(pd.read_parquet(STRATA).query("stratum=='intervened'").item_id)
    corpus = pd.read_parquet(CORPUS).set_index("item_id")
    df = phase5.load_main()
    df = df[(df.dataset != "ptcs") | df.item_id.isin(interv)]
    base = df[(df.model == "qwen3.5") & (df.context_level == "with_guidance")
              & (df.scope == "question_by_question") & (df.decomposition == "holistic")]
    lines = [r"% AUTO-GENERATED by experiments/analysis/make_datasets_table.py -- do not hand-edit.",
             r"\begin{table*}[!tb]", r"\centering", r"\footnotesize",
             r"\caption{The datasets. Every answer is graded with reasoning off; Sampled is the fixed random "
             r"subset also graded with reasoning on. Published results come from different models, prompts, and "
             r"protocols, so they situate each dataset and are not compared with ours. QWK: quadratic weighted "
             r"kappa; EN, English; PT, Portuguese.}",
             r"\label{tab:datasets}", r"\setlength{\tabcolsep}{4pt}",
             r"\begin{tabular}{@{}l l r r l l l@{}}", r"\hline",
             r"Set & Domain & Answers & Sampled & Human grade & Guidance & Published \\",
             r"\hline"]
    exams = None
    for key, label, dom, grade, guid, pub in ROWS:
        ds, d = key.split(":")
        off = base[(base.dataset == ds) & (base.domain == d) & (base.reasoning == "off")]
        on = base[(base.dataset == ds) & (base.domain == d) & (base.reasoning == "on")]
        items = sorted(off.item_id.unique())
        q = corpus.loc[items, "question_id"].nunique()
        unit = {"riayn": "problems"}.get(ds, "questions")
        size = f"{len(items)} ({q} {unit})"
        if ds == "ptcs":
            pt = sorted(base[(base.dataset == "ptcs") & (base.reasoning == "off")].item_id.unique())
            exams = corpus.loc[pt, "submission_id"].nunique()
        lines.append(f"{label} & {dom} & {size} & {on.item_id.nunique()} & {grade} & {guid} & {pub} \\\\")
        print(f"  {label:12} answers={len(items)} {unit}={q} reasoning_sample={on.item_id.nunique()}")
    lines += [r"\hline", r"\end{tabular}", "",
              r"\vspace{2pt}",
              rf"\parbox{{0.95\textwidth}}{{\scriptsize PT-CS: {exams} complete exams; scores are normalised "
              r"to $[0,1]$ before any analysis, since question weights range from 1 to 12 points.}",
              r"\end{table*}"]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"  PT-CS exams={exams}\nwrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
